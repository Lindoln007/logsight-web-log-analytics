def _inject(rng: random.Random, payload: str, params: list[str]) -> str:
    """Place *payload* into a request target the way real attacks do."""
    payload = payload.replace("{v}", rng.choice(["1", "1", "5", "42", "100", "abc", "test", ""]))
    encoded = _encode(rng, payload)
    name = rng.choice(params)
    shape = rng.random()
    if shape < 0.70:
        extra = f"&{rng.choice(PARAM_NAMES)}={rng.randint(1, 500)}" if rng.random() < 0.3 else ""
        lead = f"{rng.choice(PARAM_NAMES)}={rng.randint(1, 500)}&" if rng.random() < 0.2 else ""
        return f"{_base_path(rng)}?{lead}{name}={encoded}{extra}"
    if shape < 0.85:
        return f"/{rng.choice(SECTIONS) or 'item'}/{encoded}"
    return f"/?{name}={encoded}"


def _attack_examples(rng: random.Random, per_pattern: int) -> list[Example]:
    examples: list[Example] = []

    for index, pattern in enumerate(SQLI):
        for _ in range(per_pattern):
            examples.append((_inject(rng, _random_case(rng, pattern), PARAM_NAMES), "sqli", f"sqli-{index}"))

    for index, pattern in enumerate(XSS):
        for _ in range(per_pattern):
            examples.append((_inject(rng, _random_case(rng, pattern), PARAM_NAMES), "xss", f"xss-{index}"))

    for index, pattern in enumerate(TRAVERSAL):
        for _ in range(per_pattern):
            examples.append((_inject(rng, pattern, FILE_PARAMS), "path_traversal", f"trav-{index}"))
    for index, target in enumerate(TRAVERSAL_PATHS):
        for _ in range(max(2, per_pattern // 3)):
            prefix = rng.choice(["", "", "/app", "/site", "/portal"])
            examples.append((prefix + target, "path_traversal", f"travpath-{index}"))

    for index, pattern in enumerate(COMMAND):
        for _ in range(per_pattern):
            examples.append((_inject(rng, pattern, CMD_PARAMS), "command_injection", f"cmd-{index}"))
    for index, target in enumerate(COMMAND_PATHS):
        for _ in range(max(2, per_pattern // 3)):
            address = f"{rng.randint(11, 223)}.{rng.randint(0, 255)}.{rng.randint(0, 255)}.{rng.randint(1, 254)}"
            examples.append((target.replace("198.51.100.7", address), "command_injection", f"cmdpath-{index}"))

    for index, probe in enumerate(PROBES):
        for _ in range(max(3, per_pattern // 2)):
            target = rng.choice(PROBE_PREFIXES) + probe
            roll = rng.random()
            if roll < 0.12 and not target.endswith("/"):
                target += rng.choice(BACKUP_SUFFIXES)
            elif roll < 0.20:
                target = _random_case(rng, target)
            elif roll < 0.26:
                target += f"?{rng.choice(['a', 'x', 'phpinfo', 'cmd', 'rand'])}={rng.randint(1, 99999)}"
            examples.append((target, "scanner_probe", f"probe-{index}"))

    return examples


