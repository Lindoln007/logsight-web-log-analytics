def build_corpus(
    *,
    seed: int = 42,
    per_pattern: int = 14,
    generated_normal: int = 6_000,
    real_normal: list[str] | None = None,
) -> list[Example]:
    """
    Return the full labelled corpus as ``(request target, class, group)`` tuples.

    *real_normal* is an optional list of genuine benign request targets
    (harvested from access logs); each becomes its own group.
    """
    rng = random.Random(seed)
    examples = _attack_examples(rng, per_pattern)

    for _ in range(generated_normal):
        target, kind = _normal(rng)
        # Group generated normals in small buckets so a held-out split still
        # contains every kind of normal URL.
        examples.append((target, "normal", f"normal-{kind}-{rng.randint(0, 39)}"))

    for index, target in enumerate(real_normal or []):
        examples.append((target, "normal", f"real-{index}"))

    rng.shuffle(examples)
    return examples
