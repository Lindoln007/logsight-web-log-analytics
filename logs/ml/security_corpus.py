def _slug(rng: random.Random, low: int = 1, high: int = 4) -> str:
    joiner = rng.choice(["-", "-", "-", "_", "+"])
    return joiner.join(rng.choice(WORDS) for _ in range(rng.randint(low, high)))


def _base_path(rng: random.Random) -> str:
    section = rng.choice(SECTIONS)
    prefix = f"/{section}" if section else ""
    return f"{prefix}/{rng.choice(SCRIPT_PAGES)}"


def _random_case(rng: random.Random, text: str) -> str:
    mode = rng.random()
    if mode < 0.55:
        return text
    if mode < 0.75:
        return text.upper()
    return "".join(ch.upper() if rng.random() < 0.5 else ch.lower() for ch in text)


def _encode(rng: random.Random, payload: str) -> str:
    """Apply one of the encodings attackers (and browsers) commonly use."""
    mode = rng.random()
    if mode < 0.35:
        return payload                                   # raw, as many scanners send it
    if mode < 0.60:
        return payload.replace(" ", "+")
    if mode < 0.85:
        return quote(payload, safe="")                   # fully percent-encoded
    if mode < 0.95:
        return quote(payload, safe="/=&?:;,()")          # partially encoded
    return quote(quote(payload, safe=""), safe="")       # double-encoded


