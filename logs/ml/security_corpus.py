def _normal(rng: random.Random) -> tuple[str, str]:
    kind = rng.random()
    section = rng.choice(SECTIONS)
    prefix = f"/{section}" if section else ""

    if kind < 0.05:
        return rng.choice(["/", "/index.html", "/robots.txt", "/favicon.ico", "/sitemap.xml",
                           "/feed/", "/rss.xml", "/about", "/contact", "/login", "/logout",
                           "/register", "/health", "/status", "/manifest.json", "/readme.html",
                           "/license.txt", "/crossdomain.xml", "/CHANGELOG.txt", "//",
                           f"/{rng.choice(WORDS)}", f"/{rng.choice(WORDS)}/"]), "landing"
    if kind < 0.09:
        # Web-server directory listings: column sort links such as ?C=M;O=D.
        folder = f"{prefix}/{_slug(rng, 1, 2)}/" if rng.random() < 0.6 else f"{prefix}/"
        return f"{folder}?C={rng.choice('NMSD')};O={rng.choice('AD')}", "dirlist"
    if kind < 0.14:
        # Classic CGI scripts and search forms with free-text queries.
        script = f"/{rng.choice(['cgi-bin', 'htbin', 'scripts', 'bin'])}/{_slug(rng, 1, 2)}{rng.choice(['.pl', '.cgi', '.py', ''])}"
        roll = rng.random()
        if roll < 0.3:
            return script, "cgi"
        if roll < 0.5:
            return f"{script}?{rng.randint(1, 600)},{rng.randint(1, 600)}", "cgi"
        joiner = rng.choice(["+", "%20", "+and+", "%20and%20", "+or+", "%20or%20"])
        return f"{script}?{joiner.join(rng.choice(WORDS) for _ in range(rng.randint(1, 4)))}", "cgi"
    if kind < 0.19:
        # Free-text search terms, including quotes and apostrophes people type.
        words = [rng.choice(WORDS) for _ in range(rng.randint(1, 5))]
        roll = rng.random()
        if roll < 0.25:
            words.insert(rng.randrange(len(words) + 1), rng.choice(["and", "or", "not", "from", "where", "select"]))
        phrase = rng.choice(["+", "%20"]).join(words)
        if roll > 0.85:
            phrase = rng.choice(["%22{}%22", "o'{}", "{}'s", "d'{}", "rock+'n'+{}"]).format(phrase)
        search_page = rng.choice(["search", "search.php", "find", "results", "index.php"])
        search_param = rng.choice(["q", "query", "s", "search", "keywords", "term"])
        return f"{prefix}/{search_page}?{search_param}={phrase}", "search"
    if kind < 0.28:
        return f"{prefix}/{_slug(rng)}{rng.choice(STATIC_EXT)}", "static"
    if kind < 0.36:
        version = f"{rng.randint(1, 9)}.{rng.randint(0, 20)}.{rng.randint(0, 9)}"
        return f"/static/{rng.choice(['js', 'css', 'img', 'fonts'])}/{_slug(rng, 1, 2)}.{rng.choice(['min.js', 'css', 'png'])}?v={version}", "versioned"
    if kind < 0.60:
        return f"{prefix}/{_slug(rng)}{rng.choice(PAGE_EXT)}", "page"
    if kind < 0.68:
        return f"{prefix}/{rng.randint(2005, 2026)}/{rng.randint(1, 12):02d}/{_slug(rng, 2, 5)}/", "dated"
    if kind < 0.76:
        return f"/api/v{rng.randint(1, 3)}/{rng.choice(WORDS)}/{rng.randint(1, 99999)}{rng.choice(['', '/comments', '/edit', '.json'])}", "rest"

    # Pages with query strings.
    params = []
    for _ in range(rng.randint(1, 3)):
        name = rng.choice(PARAM_NAMES + ["utm_source", "utm_campaign", "date", "token", "email", "min", "max", "callback", "format"])
        value_kind = rng.random()
        if name in ("redirect", "url", "next"):
            value = rng.choice([f"/{_slug(rng)}", f"https://www.example.com/{_slug(rng)}", f"%2F{_slug(rng)}%2F"])
        elif name == "email":
            value = f"{rng.choice(WORDS)}%40example.com"
        elif name == "date":
            value = f"{rng.randint(2010, 2026)}-{rng.randint(1, 12):02d}-{rng.randint(1, 28):02d}"
        elif name == "token":
            value = "".join(rng.choice("0123456789abcdef") for _ in range(rng.choice([16, 32, 40])))
        elif name in ("file", "path", "doc"):
            value = f"{_slug(rng, 1, 2)}{rng.choice(['.pdf', '.txt', '.docx', '.csv', ''])}"
        elif value_kind < 0.4:
            value = str(rng.randint(0, 99999))
        elif value_kind < 0.8:
            value = _slug(rng, 1, 4)
        else:
            value = rng.choice(["asc", "desc", "en", "fr", "true", "false", "json", "all", "newest"])
        params.append(f"{name}={value}")
    return f"{prefix}/{rng.choice(SCRIPT_PAGES + [_slug(rng, 1, 2)])}?{'&'.join(params)}", "query"


